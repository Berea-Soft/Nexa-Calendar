const locales = new Map<LocaleCode, Locale>();

export function registerLocale(code: LocaleCode, locale: Locale): void {
  locales.set(code, locale);
}

export function getLocale(code: LocaleCode): Locale {
  return locales.get(code) ?? enLocale;
}

export function getAvailableLocales(): LocaleCode[] {
  return Array.from(locales.keys());
}

